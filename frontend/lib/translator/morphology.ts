export function getVerb(word: string): VerbEntry | undefined {
  return verbs[word];
}

export function analyzeNoun(word: string): string {
  const suffixes = [
    "हरूबाट",
    "हरूसँग",
    "हरूलाई",
    "हरूमा",
    "हरूको",
    "हरूकी",
    "हरूका",
    "हरूले",
    "हरू",
    "बाट",
    "सँग",
    "लाई",
    "मा",
    "ले",
    "को",
    "की",
    "का",
  ];

  let root = word;
  let changed = true;

  while (changed) {
    changed = false;

    for (const suffix of suffixes) {
      if (root.endsWith(suffix) && root.length > suffix.length) {
        root = root.slice(0, -suffix.length);
        changed = true;
        break;
      }
    }
  }

  return root;
}
